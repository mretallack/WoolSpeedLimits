#!/usr/bin/env python3
"""
build_20mph_net.py — Build wool.20mph.net.xml (Option A) from the Dorset Council
consultation (Sources/Wool20MphRoads.json).

Method: match consultation streets to network edges by NAME (using a named
network generated by netconvert --output.street-names) confirmed by GEOMETRY
OVERLAP, then set to 20mph only the matched edges currently at 30/31 mph
(Option A), leaving higher-speed edges unchanged.

Prereq: /tmp/wool_named.net.xml, produced by netconvert (see NETWORK_BUILD.md).

Usage: python3 build_20mph_net.py
"""
import html
import json
import math
import os
import sys
import xml.etree.ElementTree as ET

CONSULT = os.path.join(os.path.dirname(__file__), "..", "Sources", "Wool20MphRoads.json")
BASELINE = "wool.net.xml"
NAMED = "/tmp/wool_named.net.xml"
OUT = "wool.20mph.net.xml"
TARGET_MS = 8.94          # 20 mph
MAX_BASELINE_MPH = 31     # Option A: only invert edges currently <= this
TOL_M = 15.0              # geometry tolerance (metres)
MIN_FRAC = 0.5            # min fraction of edge vertices inside the segment
ALIAS = {"Macville Avenue": "MacVille Ave", "Breach Field": "Breach Field Road"}


def ll_to_utm(lat, lon):
    """WGS84 lat/lon -> UTM zone 30N easting/northing (pure python)."""
    a = 6378137.0; f = 1 / 298.257223563; e2 = f * (2 - f); k0 = 0.9996
    lon0 = math.radians(-3.0)
    lat, lon = math.radians(lat), math.radians(lon)
    N = a / math.sqrt(1 - e2 * math.sin(lat) ** 2)
    T = math.tan(lat) ** 2; C = e2 / (1 - e2) * math.cos(lat) ** 2
    A = (lon - lon0) * math.cos(lat)
    M = a * ((1 - e2 / 4 - 3 * e2 ** 2 / 64 - 5 * e2 ** 3 / 256) * lat
             - (3 * e2 / 8 + 3 * e2 ** 2 / 32 + 45 * e2 ** 3 / 1024) * math.sin(2 * lat)
             + (15 * e2 ** 2 / 256 + 45 * e2 ** 3 / 1024) * math.sin(4 * lat)
             - (35 * e2 ** 3 / 3072) * math.sin(6 * lat))
    east = k0 * N * (A + (1 - T + C) * A ** 3 / 6 + (5 - 18 * T + T * T) * A ** 5 / 120) + 500000.0
    north = k0 * (M + N * math.tan(lat) * (A * A / 2 + (5 - T + 9 * C) * A ** 4 / 24
                                           + (61 - 58 * T + T * T) * A ** 6 / 720))
    return east, north


def pt_seg(p, a, b):
    px, py = p; ax, ay = a; bx, by = b
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = max(0, min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def main():
    if not os.path.exists(NAMED):
        sys.exit(f"missing {NAMED}; run netconvert first (see NETWORK_BUILD.md)")

    base = ET.parse(BASELINE).getroot()
    ox, oy = [float(x) for x in base.find("location").get("netOffset").split(",")]

    # edge shapes and baseline speeds from wool.net.xml
    shape, speed_mph = {}, {}
    for e in base.findall("edge"):
        if e.get("function") == "internal":
            continue
        lane = e.find("lane")
        if lane is None:
            continue
        shape[e.get("id")] = [(float(p.split(",")[0]), float(p.split(",")[1]))
                              for p in lane.get("shape").split()]
        speed_mph[e.get("id")] = float(lane.get("speed")) * 2.23694

    # street names from the named net (same edge IDs)
    name_of = {}
    for e in ET.parse(NAMED).getroot().findall("edge"):
        if e.get("function") == "internal":
            continue
        if e.get("name"):
            name_of[e.get("id")] = html.unescape(e.get("name"))

    # consultation segments (projected to net coords), grouped by street
    cons = json.load(open(CONSULT))
    seg_by_street = {}
    for f in cons["data"]["features"]:
        for s in [x.strip() for x in (f["properties"].get("streetName") or "").split(",") if x.strip()]:
            cpts = [(lambda e, n: (e + ox, n + oy))(*ll_to_utm(lat, lon))
                    for lon, lat in f["geometry"]["coordinates"]]
            seg_by_street.setdefault(s, []).append(cpts)

    def frac_within(segs, ep):
        if not ep:
            return 0.0
        hit = sum(1 for p in ep
                  if min(min(pt_seg(p, cs[i], cs[i + 1]) for i in range(len(cs) - 1))
                         for cs in segs) <= TOL_M)
        return hit / len(ep)

    # name + geometry match
    matched = set()
    for s, segs in seg_by_street.items():
        nn = ALIAS.get(s, s)
        for eid, nm in name_of.items():
            if nm == nn and eid in shape and frac_within(segs, shape[eid]) >= MIN_FRAC:
                matched.add(eid)

    # Option A: keep only edges currently <= MAX_BASELINE_MPH
    to20 = sorted(e for e in matched if eid_ok(e, speed_mph))
    anomalies = sorted(e for e in matched if not eid_ok(e, speed_mph))

    # write the 20mph net
    ET.register_namespace("", "")
    tree = ET.parse(BASELINE)
    root = tree.getroot()
    for e in root.findall("edge"):
        if e.get("id") in set(to20):
            for lane in e.findall("lane"):
                lane.set("speed", f"{TARGET_MS:.2f}")
    tree.write(OUT, encoding="UTF-8", xml_declaration=True)

    print(f"matched edges: {len(matched)}")
    print(f"set to 20mph (Option A, <= {MAX_BASELINE_MPH} mph): {len(to20)}")
    print(f"left unchanged (higher speed anomalies): {len(anomalies)} -> {anomalies}")
    print(f"wrote {OUT}")


def eid_ok(eid, speed_mph):
    return eid in speed_mph and round(speed_mph[eid]) <= MAX_BASELINE_MPH


if __name__ == "__main__":
    main()
